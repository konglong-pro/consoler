const smokeDir = fs.mkdtempSync(path.join(os.tmpdir(), "consoler-sdk-smoke-"));
const smokeScript = path.join(smokeDir, "package_smoke_adapter.py");
fs.writeFileSync(smokeScript, SMOKE_ADAPTER, "utf8");

function rpcSession(requests, waitForResponseIds = []) {
  return new Promise((resolve, reject) => {
    const child = spawn(venvPython, [smokeScript], {
      env: venvEnv,
      stdio: ["pipe", "pipe", "pipe"],
      windowsHide: true
    });
    const messages = [];
    let buffer = "";
    const pending = new Set(waitForResponseIds);
    let stdinClosed = false;

    function maybeCloseStdin() {
      if (!stdinClosed && (waitForResponseIds.length === 0 || pending.size === 0)) {
        stdinClosed = true;
        child.stdin.end();
      }
    }

    child.stdout.on("data", (chunk) => {
      buffer += chunk.toString();
      const lines = buffer.split(/\r?\n/);
      buffer = lines.pop() ?? "";
      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed) {
          continue;
        }
        try {
          const message = JSON.parse(trimmed);
          messages.push(message);
          if (message.id !== undefined && pending.has(message.id)) {
            pending.delete(message.id);
          }
          maybeCloseStdin();
        } catch (error) {
          reject(error);
        }
      }
    });

    child.stderr.on("data", (chunk) => {
      process.stderr.write(chunk);
    });

    child.on("error", reject);

    child.on("close", (code) => {
      if (code !== 0) {
        reject(new Error(`smoke adapter exited ${code}`));
        return;
      }
      resolve(messages);
    });

    for (const request of requests) {
      child.stdin.write(`${JSON.stringify(request)}\n`);
    }
    maybeCloseStdin();
  });
}

const syncResponses = await rpcSession(
  [
  { jsonrpc: "2.0", id: 1, method: "agent.health", params: {} },
  { jsonrpc: "2.0", id: 2, method: "agent.discover", params: {} },
  {
    jsonrpc: "2.0",
    id: 3,
    method: "agent.validate",
    params: { command: "smoke.ping", args: {} }
  },
  {
    jsonrpc: "2.0",
    id: 4,
    method: "agent.plan",
    params: { command: "smoke.ping", args: {}, action_id: "act_1" }
  },
  {
    jsonrpc: "2.0",
    id: 5,
    method: "agent.preview",
    params: { command: "smoke.ping", args: {}, plan: { steps: [] } }
  },
  {
    jsonrpc: "2.0",
    id: 6,
    method: "agent.get_artifact_view",
    params: {
      artifact_uri: "fake://x",
      kind: "text/plain",
      block_id: "b1",
      action_id: "act_1"
    }
  }
  ],
  [1, 2, 3, 4, 5, 6]
);

function responseForId(id) {
  const message = syncResponses.find((entry) => entry.id === id);
  if (!message) {
    fail(`missing JSON-RPC response for id ${id}`);
  }
  return message;
}

const health = responseForId(1);
if (health.result?.status !== "ok") {
  fail(`agent.health expected status ok, got ${JSON.stringify(health)}`);
}

const discover = responseForId(2);
if (discover.result?.agent_id !== "package-smoke") {
  fail(`agent.discover expected package-smoke agent_id, got ${JSON.stringify(discover)}`);
}

if (responseForId(3).error || responseForId(4).error || responseForId(5).error) {
  fail("agent.validate/plan/preview should succeed for smoke.ping");
}

const artifact = responseForId(6);
if (!artifact.error) {
  fail("agent.get_artifact_view should be unsupported by default adapter");
}

const executeMessages = await rpcSession(
  [
    {
      jsonrpc: "2.0",
      id: 10,
      method: "agent.execute",
      params: {
        run_id: "run_1",
        action_id: "act_1",
        command: "smoke.ping",
        args: {},
        plan: { steps: [{ step_id: "s1", title: "Ping" }] }
      }
    }
  ],
  [10]
);

const executeResult = executeMessages.find((entry) => entry.id === 10);
if (!executeResult?.result?.ok) {
  fail(`agent.execute should succeed, got ${JSON.stringify(executeResult)}`);
}

const eventTypes = executeMessages
  .filter((entry) => entry.method === "agent.event")
  .map((entry) => entry.params?.event?.type)
  .filter(Boolean);

if (!eventTypes.includes("action.started") || !eventTypes.includes("action.succeeded")) {
  fail(
    `agent.execute should emit action.started and action.succeeded, got ${eventTypes.join(", ") || "(none)"}`
  );
}

console.log("\nPython SDK package gate passed");
